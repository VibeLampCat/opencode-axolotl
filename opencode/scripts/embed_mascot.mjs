import fs from "node:fs"
import path from "node:path"
import zlib from "node:zlib"
import crypto from "node:crypto"
import { fileURLToPath } from "node:url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const rootDir = path.resolve(__dirname, "..")
const targetPath = path.resolve(rootDir, "packages", "util", "src", "argon-embedded.gen.ts")

function ensureParentDir(filePath) {
  const dir = path.dirname(filePath)
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true })
  }
}

function writeStub() {
  ensureParentDir(targetPath)
  const content = `// Auto-generated by scripts/embed_mascot.mjs - DO NOT EDIT MANUALLY
export const EMBEDDED_MASCOT_GZ_BASE64 = ""
export const EMBEDDED_MASCOT_SHA256 = ""
`
  fs.writeFileSync(targetPath, content, "utf-8")
  console.log(`[embed_mascot] Generated stub at ${targetPath}`)
}

function embedBinary(binaryPath) {
  const resolvedBinPath = path.resolve(process.cwd(), binaryPath)
  if (!fs.existsSync(resolvedBinPath)) {
    console.error(`[embed_mascot] Error: Binary file not found: ${resolvedBinPath}`)
    process.exit(1)
  }

  const rawBuffer = fs.readFileSync(resolvedBinPath)
  const sha256 = crypto.createHash("sha256").update(rawBuffer).digest("hex")
  const gzipped = zlib.gzipSync(rawBuffer, { level: 9 })
  const base64Str = gzipped.toString("base64")

  ensureParentDir(targetPath)
  const content = `// Auto-generated by scripts/embed_mascot.mjs - DO NOT EDIT MANUALLY
export const EMBEDDED_MASCOT_GZ_BASE64 = "${base64Str}"
export const EMBEDDED_MASCOT_SHA256 = "${sha256}"
`
  fs.writeFileSync(targetPath, content, "utf-8")

  const rawMb = (rawBuffer.length / (1024 * 1024)).toFixed(2)
  const gzMb = (gzipped.length / (1024 * 1024)).toFixed(2)
  console.log(`[embed_mascot] Successfully embedded ${resolvedBinPath}:`)
  console.log(`  Raw size:        ${rawMb} MB (${rawBuffer.length} bytes)`)
  console.log(`  Gzip size:       ${gzMb} MB (${gzipped.length} bytes)`)
  console.log(`  SHA-256:         ${sha256}`)
  console.log(`  Output file:     ${targetPath}`)
}

const arg = process.argv[2]
if (!arg || arg === "--stub") {
  writeStub()
} else {
  embedBinary(arg)
}
